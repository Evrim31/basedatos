DROP TABLE MIS_LIBROS CASCADE CONSTRAINTS;
DROP TABLE AUTORES CASCADE CONSTRAINTS;
DROP TABLE EDITORIALES CASCADE CONSTRAINTS;

CREATE TABLE EDITORIALES (
ID NUMBER,
NOMBRE VARCHAR2(50)
);

CREATE TABLE MIS_LIBROS (
ISBM NUMBER PRIMARY KEY,
NOMBRE VARCHAR2(50),
AUTOR NUMBER,
EDITORIA NUMBER,
FECHA_PUBLICACION DATE
);

CREATE TABLE AUTORES (
NOMBRE VARCHAR2(50),
APELLIDOS VARCHAR2(50),
NACIONALIDAD VARCHAR2(50),
PAREJA VARCHAR2(50)
);

